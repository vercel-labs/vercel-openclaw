import assert from 'node:assert/strict';
import { nativeSlackPrompt, sha256 } from './native-slack-proof.mjs';

export function verifyNativeIdle({ fixture, observations, idle, logs, runtimeDigest }) {
  assert.deepEqual(fixture.cases, [{ label: 'write', role: 'write' }, { label: 'warm', role: 'read' }, { label: 'wake', role: 'read' }]);
  const suffix = fixture.senderAttributionUser ? ` *Sent using* <@${fixture.senderAttributionUser}>` : '';
  const runs = fixture.cases.map(test => {
    const o = observations[test.label];
    assert.equal(o.runtimeDigest, runtimeDigest);
    assert.equal(o.thread, fixture.thread);
    const input = o.messages.find(m => m.ts === o.timestamp);
    assert.equal(input?.user, fixture.user);
    assert.equal(input.text.trim(), nativeSlackPrompt(fixture, test.role) + suffix);
    if (test.role === 'read') assert(!input.text.includes(fixture.value));
    const admissions = o.admissions.filter(a => a.type === 'admitted' && a.at >= Number(o.timestamp) * 1000);
    assert.equal(admissions.length, 1);
    const eventId = admissions[0].eventId;
    const receipts = logs.filter(l => l.message?.startsWith('codex lifecycle receipt ')).map(l => JSON.parse(l.message.slice('codex lifecycle receipt '.length))).filter(r => r.eventId === eventId);
    assert.equal(receipts.length, 1);
    const r = receipts[0];
    assert.equal(r.gatewayStopped, false);
    assert.equal(r.vm1Stopped, false);
    assert.equal(r.nativeSlackDelivered, true);
    assert.equal(r.idleTimeoutMs, 2700000);
    const delivered = o.admissions.filter(a => a.type === 'delivered' && a.eventId === eventId);
    assert.equal(delivered.length, 1);
    const reply = o.messages.find(m => m.ts === delivered[0].messageId);
    assert.equal(reply?.user, fixture.bot);
    assert(reply.text.includes(fixture.value) && Number(reply.ts) > Number(input.ts));
    const last = o.observations.at(-1);
    assert.equal(last.status, 'running');
    assert.equal(last.vmSession, r.platformSessionId);
    assert.equal(last.eyes, false);
    assert(o.observations.some(s => s.eyes));
    assert.equal(last.worker?.name, r.workerName);
    assert.equal(last.worker.status, 'running');
    assert.equal(last.worker.persistent, false);
    assert.equal(last.worker.fileSha256, sha256(fixture.value + '\n'));
    return { ...r, timestamp: o.timestamp, replyMs: Number(reply.ts) * 1000 - Number(input.ts) * 1000 };
  });
  assert.equal(new Set(runs.map(r => r.eventId)).size, 3);
  assert.equal(new Set(runs.map(r => r.sessionId)).size, 1);
  assert.equal(runs[0].platformSessionId, runs[1].platformSessionId);
  assert.equal(runs[0].gatewayPid, runs[1].gatewayPid);
  assert.equal(runs[0].workerName, runs[1].workerName);
  assert.equal(runs[1].workerReused, true);
  assert(Number(runs[1].timestamp) * 1000 > observations.write.observations.at(-1).at);
  assert.equal(idle.snapshot.status, 'created');
  assert.equal(idle.snapshot.sourceSessionId, runs[1].platformSessionId);
  assert.equal(idle.observations.at(-1).status, 'stopped');
  assert.equal(idle.worker.name, runs[1].workerName);
  assert.equal(idle.worker.status, 'stopped');
  assert(idle.observations.at(-1).at - observations.warm.observations.at(-1).at >= 45 * 60_000 - 10_000, 'Full idle interval was not observed');
  const sleepReceipts = logs.filter(l => l.message?.startsWith('codex sleep receipt ')).map(l => JSON.parse(l.message.slice('codex sleep receipt '.length))).filter(r => r.platformSessionId === runs[1].platformSessionId && r.action === 'sleep');
  assert.equal(sleepReceipts.length, 1);
  assert.equal(sleepReceipts[0].reason, 'idle', 'A hard-deadline stop is not proof of 45-minute inactivity');
  assert.equal(sleepReceipts[0].snapshotId, idle.snapshot.id);
  assert(Number(runs[2].timestamp) * 1000 > idle.observations.at(-1).at);
  assert.notEqual(runs[1].platformSessionId, runs[2].platformSessionId);
  assert.notEqual(runs[1].workerName, runs[2].workerName);
  return runs;
}
